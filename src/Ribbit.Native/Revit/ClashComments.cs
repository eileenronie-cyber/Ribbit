using System.IO;
using System.Text.Json;
using Ribbit.Geometry.Clash;

namespace Ribbit.Native.Revit;

/// <summary>One note, and when it was last written.</summary>
internal sealed class ClashComment
{
    public string Text { get; set; } = "";

    /// <summary>Round-trip "o" format. Answers "was this note before or after the fix?".</summary>
    public string WhenUtc { get; set; } = "";
}

/// <summary>
/// A note per clash — the "why" that a status on its own cannot carry.
///
/// A status says Accepted. Three weeks later the only question anyone has is why,
/// and until now nothing in the system could answer it. This is that answer.
///
/// KEYED BY CLASH PAIR, exactly like status. The two travel together: the note
/// explaining a decision must attach to the same thing the decision attached to,
/// or a pipe against three beams gets one note that appears to explain all three.
///
/// STORED BESIDE THE REPORTS, NOT IN THEM. The report CSV is a shared format the
/// Python tools read by column, so it gains no columns here. A separate file also
/// means a note survives a report being deleted, which matters because notes are
/// the one thing in this system that cannot be regenerated by re-running.
///
/// That last point is why the fail-open contract here is STRICTER than
/// <see cref="SeenLedger"/>'s. Losing a baseline costs a badge; losing notes
/// costs work nobody can reconstruct. A file that will not parse is preserved,
/// never silently overwritten.
/// </summary>
internal sealed class ClashComments
{
    /// <summary>Clash pair key to its note.</summary>
    public Dictionary<string, ClashComment> ByClash { get; set; } = [];

    /// <summary>
    /// A file existed but could not be read.
    ///
    /// Not serialized: it describes THIS load, not the data. Save moves the
    /// unreadable file aside instead of writing over it, so a stray character
    /// costs you the notes only until someone opens the file and fixes it.
    /// </summary>
    [System.Text.Json.Serialization.JsonIgnore]
    public bool Corrupt { get; set; }

    /// <summary>
    /// Keys this editor set or cleared since it loaded - the only notes its
    /// <see cref="Save"/> may change.
    ///
    /// It used to merge by "keep mine, add what I never loaded", so every note
    /// this copy merely LOADED was written back as it was at load: a colleague
    /// who edited or deleted that note in the meantime had it silently undone
    /// the next time this editor saved anything at all. Proven by
    /// ClashCommentsTests (an edit came back as the old text, a deletion came
    /// back).
    /// </summary>
    [System.Text.Json.Serialization.JsonIgnore]
    private HashSet<string> _changed = [];

    /// <summary>
    /// The file as it stands now: an empty dictionary when there is no file,
    /// NULL when there is one and it cannot be read.
    ///
    /// The two must not be confused. Save rebuilds the file from what is on
    /// disk plus this editor's own changes, so "unreadable" answered as "empty"
    /// wrote a file holding only those changes - every other note gone because
    /// a colleague's save, or a cloud sync, had the file in a half-written state
    /// for a moment.
    /// </summary>
    private static Dictionary<string, ClashComment>? ReadFromDisk(string path)
    {
        try
        {
            if (!File.Exists(path))
                return [];

            return JsonSerializer.Deserialize<ClashComments>(File.ReadAllText(path))?.ByClash ?? [];
        }
        catch (Exception)
        {
            return null;
        }
    }

    private static string PathFor(string csvFolder, string? modelTitle, string productTag)
        => Path.Combine(
            csvFolder, ClashStatus.ModelCsvPrefix(modelTitle, productTag) + "comments.json");

    public static ClashComments Load(string? csvFolder, string? modelTitle, string productTag)
    {
        if (string.IsNullOrEmpty(csvFolder) || !Directory.Exists(csvFolder))
            return new ClashComments();

        string path = PathFor(csvFolder!, modelTitle, productTag);
        if (!File.Exists(path))
            return new ClashComments();

        try
        {
            ClashComments? loaded =
                JsonSerializer.Deserialize<ClashComments>(File.ReadAllText(path));

            if (loaded is not null)
            {
                loaded.ByClash ??= [];
                return loaded;
            }
        }
        catch (Exception)
        {
            // Falls through to the corrupt path below.
        }

        return new ClashComments { Corrupt = true };
    }

    public string TextFor(string? clashKey)
        => !string.IsNullOrEmpty(clashKey) && ByClash.TryGetValue(clashKey!, out ClashComment? c)
            ? c.Text
            : "";

    /// <summary>
    /// Sets or clears a note. Blank REMOVES the entry rather than storing an
    /// empty one, so "has a note" stays a question the file can answer.
    /// </summary>
    public void Set(string clashKey, string text)
    {
        if (clashKey.Length == 0)
            return;

        string trimmed = (text ?? "").Trim();

        _changed.Add(clashKey);

        if (trimmed.Length == 0)
        {
            ByClash.Remove(clashKey);
            return;
        }

        ByClash[clashKey] = new ClashComment
        {
            Text = trimmed,
            WhenUtc = DateTime.UtcNow.ToString("o"),
        };
    }

    /// <summary>
    /// Takes a note as it is, keeping its own timestamp - for a merge carrying
    /// notes over from another file. Counts as this editor's change, so
    /// <see cref="Save"/> writes it; an assignment straight into
    /// <see cref="ByClash"/> would be overwritten by the file on disk.
    /// </summary>
    public void Put(string clashKey, ClashComment note)
    {
        if (clashKey.Length == 0)
            return;

        ByClash[clashKey] = note;
        _changed.Add(clashKey);
    }

    /// <summary>
    /// Writes the notes. Returns null on success, or why it failed.
    ///
    /// Unlike the baseline, a failure here is REPORTED rather than swallowed:
    /// a note the user typed and believes is saved must not vanish quietly.
    /// </summary>
    public string? Save(string? csvFolder, string? modelTitle, string productTag)
    {
        if (string.IsNullOrEmpty(csvFolder) || !Directory.Exists(csvFolder))
            return "no folder to write to";

        string path = PathFor(csvFolder!, modelTitle, productTag);

        try
        {
            // Move the unreadable file aside before writing over its name. It is
            // the only copy of whatever was in there.
            if (Corrupt && File.Exists(path))
            {
                string aside = path + ".unreadable";
                File.Delete(aside);
                File.Move(path, aside);
                Corrupt = false;
            }
            else
            {
                // MERGED PER CLASH, like the set and test libraries. This file
                // lives in the SHARED folder, and a note is typed and then
                // believed saved - a wholesale write means the colleague who
                // added one while this editor was open loses it with no error.
                // The file on disk is the truth for every note this editor did
                // NOT touch - including a colleague's newer edit or deletion of a
                // note this copy merely loaded. Only this editor's own changes
                // (set or cleared) are applied on top.
                Dictionary<string, ClashComment>? disk = ReadFromDisk(path);

                // Unreadable NOW (it read fine at load, or Corrupt would be set):
                // fall back to what this editor loaded plus its own changes,
                // which loses nothing anyone could see a moment ago, and keep
                // the unreadable file beside it - it may hold a newer note.
                if (disk is null)
                {
                    string aside = path + ".unreadable";
                    File.Delete(aside);
                    File.Move(path, aside);
                    disk = new Dictionary<string, ClashComment>(ByClash);
                }

                Dictionary<string, ClashComment> merged = disk;
                foreach (string key in _changed)
                {
                    if (ByClash.TryGetValue(key, out ClashComment? mine))
                        merged[key] = mine;
                    else
                        merged.Remove(key);
                }

                ByClash = merged;
            }

            // Temp-then-swap, for the same reason as every other write into this
            // folder: WriteAllText truncates at open, and a reader landing in
            // that window sees a partial file, marks itself Corrupt, and moves
            // a perfectly good file aside as unreadable. See AtomicFile.
            string temp = AtomicFile.TempPathFor(path);
            File.WriteAllText(
                temp,
                JsonSerializer.Serialize(this, new JsonSerializerOptions { WriteIndented = true }));
            AtomicFile.Commit(temp, path);

            _changed.Clear();
            return null;
        }
        catch (Exception ex)
        {
            return ex.Message;
        }
    }
}
